package com.Exercise.Moodle1;

public class NotasArquitectura {
    /*JAVA 8 (Legacy)
      Introdujo lambdas y programación funcional básica.
      Uso fuerte de clases tradicionales y código más verboso.
      No tenía tantas optimizaciones en rendimiento ni nuevas APIs modernas.
      Garbage Collector menos optimizado.
      Muy usado en sistemas antiguos (legacy). */
    
    /*JAVA 17 / 21 (LTS - Long Term Support)
      Mejor rendimiento general de la JVM.
      Nuevas características como:
          - Records (menos código para modelos)
          - Pattern Matching
          - Switch mejorado
      Garbage Collector más eficiente (ZGC, G1 mejorado).
      Mejor manejo de memoria y concurrencia.
      Código más limpio, expresivo y mantenible. */  
}
